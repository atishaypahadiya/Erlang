// Writes docs/reference/ from the source (scripts/reference/collect.js reads
// the facts; this file lays them out). The pages follow the code: the command
// (bin/erlang.js, lib/erlang.js), the checks in the order lib/erlang.js runs
// them, the exit codes, the output and its schemas, the config, and what the
// scan reads.
//
// Usage: node scripts/reference.mjs           write docs/reference/
//        node scripts/reference.mjs --check   exit 1 when a committed page
//                                             differs from what the source gives

import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';
import { collect } from './reference/collect.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'docs', 'reference');
const read = (p) => readFileSync(join(ROOT, p), 'utf8');
const facts = collect({ read, ts });

const esc = (s) => String(s).replaceAll('|', '\\|').replace(/\s+/g, ' ').trim();
const code = (s) => (String(s).includes('`') ? `\`\` ${s} \`\`` : `\`${s}\``);
const table = (head, rows) => [`| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`, ...rows.map((r) => `|${r.map(esc).map((c) => (c ? ` ${c} ` : ' ')).join('|')}|`)].join('\n');
const page = (title, from, body) => `# ${title}\n\nGenerated by \`scripts/reference.mjs\` from ${from}.\n\n${body.trim()}\n`;

const PAGES = {};

{
  const c = facts.commands;
  PAGES['commands.md'] = page('Commands and flags', '`lib/erlang.js`, `package.json`, `scripts/trace.sh` and `scripts/load.sh`', `
## The command

The usage line, as the command prints it:

\`\`\`text
${c.usage}
\`\`\`

${table(['Argument', 'Meaning'], c.flags.map((f) => [code(f.flag), f.means]))}

${c.other}

The version line has this form:

\`\`\`text
${c.version}
\`\`\`

Without \`--out\`, the report is written inside the Erlang directory at the path \`join(ROOT, ${c.reportAt})\`, that is \`dist/reports/<name of dir>/report.json\`.

## Package scripts

${table(['Script', 'Runs'], c.scripts.map((s) => [code(`npm run ${s.name}`), code(s.cmd)]))}

## Harnesses

${c.harness.map((h) => `### ${code(h.file)}\n\n${h.usage}\n\n${h.exits}`).join('\n\n')}
`);
}

{
  const body = facts.checks.map((k) => {
    const parts = [`## ${k.names.map(code).join(' and ')}`, `Source: ${code(k.file)}.`, `Rules named in the source: ${k.rules.join(', ') || 'none'}.`];
    if (k.strength) parts.push(`Strength: ${k.strength}.`);
    if (k.thresholds.length) parts.push(table(['Constant', 'Value', 'Meaning'], k.thresholds.map((t) => [code(t.name), String(t.value), t.means])));
    for (const s of k.sets) parts.push(`${s.what} (${code(s.name)}): ${s.items.map((i) => code(i)).join(', ')}.`);
    return parts.join('\n\n');
  }).join('\n\n');
  PAGES['checks.md'] = page('Checks and thresholds', 'each check module, in the order of `CHECKS` in `lib/erlang.js`', `
The checks run in this order. For each, the rule ids its source names, its strength where the source states one, its named numeric constants and the named sets of forms it recognises.

${body}
`);
}

PAGES['exit-codes.md'] = page('Exit codes', '`lib/erlang.js`, `lib/crash.js` and `bin/erlang.js`', `
These are the codes of \`erlang <dir>\`. A finding fails a run when its severity is \`error\` or \`warning\`; \`info\` never does.

${table(['Code', 'Meaning', 'Source'], facts.exitCodes.map((e) => [String(e.code), e.means, e.from]))}
`);

{
  const o = facts.output;
  const schemas = o.schemas.map((s) => `## ${code(s.file)}\n\n${esc(s.title)}${s.description ? `. ${esc(s.description)}` : ''}\n\n${table(['Field', 'Type', 'Required', 'Description'], s.rows.map((r) => [code(r.name), r.type, r.required ? 'yes' : 'no', r.description]))}`).join('\n\n');
  PAGES['output.md'] = page('Output format', '`lib/erlang.js` and the schemas named below', `
## Standard output

One line per finding, from this template:

\`\`\`text
${o.stdout.line}
\`\`\`

Then one summary line, which begins with this template, followed by the reason when there is one and the report's path:

\`\`\`text
${o.stdout.summary}
\`\`\`

The report file is a report/1 document holding finding/1 findings, each with Erlang's own fields under \`erlang\`.

${schemas}
`);
}

{
  const c = facts.config;
  PAGES['config.md'] = page('Config keys', `\`${c.file}\``, `
The config is read from ${c.at}. ${esc(c.description)} Keys not listed here are refused.

${table(['Key', 'Type', 'Required', 'Description'], c.rows.map((r) => [code(r.name), r.type, r.required ? 'yes' : 'no', r.description]))}
`);
}

{
  const l = facts.limits;
  PAGES['limits.md'] = page('Limits', '`lib/sources.js` and `lib/handlers.js`', `
## Files read

- Source files are those whose names match ${code(l.source)}.
- Directories with these names are not read, wherever they are: ${l.dirs.map(code).join(', ')}.
- Symbolic links are not followed.
- A file larger than ${l.bytes} bytes is not read, and the report is partial.

## Request handlers found without configuration

${table(['Framework', 'Forms'], l.handlers.map((h) => [h.framework, h.forms]))}
`);
}

const ORDER = ['commands.md', 'checks.md', 'exit-codes.md', 'output.md', 'config.md', 'limits.md'];
PAGES['README.md'] = `# Reference

Generated by \`scripts/reference.mjs\` from the source, in the order the code is organised.

${ORDER.map((f) => `- [${PAGES[f].split('\n')[0].replace(/^# /, '')}](${f})`).join('\n')}
`;

const check = process.argv.includes('--check');
const differ = [];
if (!check) mkdirSync(OUT, { recursive: true });
for (const [name, text] of Object.entries(PAGES)) {
  const at = join(OUT, name);
  if (check) { if (!existsSync(at) || readFileSync(at, 'utf8') !== text) differ.push(name); } else writeFileSync(at, text);
}
const extra = existsSync(OUT) ? readdirSync(OUT).filter((f) => !(f in PAGES)) : [];
if (check) {
  for (const f of extra) differ.push(`${f} (not generated)`);
  if (differ.length) { console.log(`reference: docs/reference/ differs from the source in ${differ.join(', ')}; run node scripts/reference.mjs`); process.exit(1); }
  console.log(`reference: docs/reference/ matches the source (${Object.keys(PAGES).length} pages)`);
} else console.log(`reference: wrote ${Object.keys(PAGES).length} pages to docs/reference/${extra.length ? `; not generated, left as they are: ${extra.join(', ')}` : ''}`);
